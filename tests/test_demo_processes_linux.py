"""Linux-only real-process checks, using isolated temporary workspaces and tags."""
from contextlib import redirect_stdout
import io
import os
from pathlib import Path
import signal
import subprocess
import sys
import tempfile
import time
import unittest
import uuid

from test_demo_processes import PROCESS_MODULE


NODE_SOURCE = '''\
import os
from pathlib import Path
import signal
import sys
import time

if sys.argv[1] == 'orphan':
    if os.fork():
        os._exit(0)

def finish(signum, frame):
    raise SystemExit(0)

signal.signal(signal.SIGINT, finish)
signal.signal(signal.SIGTERM, finish)
ready = Path(sys.argv[2])
temporary = ready.with_name(ready.name + '.tmp')
temporary.write_text(str(os.getpid()))
temporary.replace(ready)
while True:
    time.sleep(0.1)
'''


@unittest.skipUnless(
    sys.platform.startswith('linux') and hasattr(os, 'pidfd_open') and
    hasattr(signal, 'pidfd_send_signal'), 'requires Linux /proc and pidfd support')
class LinuxProcessShutdownTests(unittest.TestCase):
    def wait_for(self, predicate, description, timeout=5.0):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            result = predicate()
            if result:
                return result
            time.sleep(0.02)
        self.fail('Timed out waiting for ' + description)

    def identity(self, pid):
        return PROCESS_MODULE.read_process(pid)

    def gone(self, expected):
        actual = self.identity(expected.pid)
        return not PROCESS_MODULE.same_identity(expected, actual) or actual.state in ('Z', 'X')

    def cleanup_owned_process(self, expected, child=None):
        """Only our pinned PID/start identity may receive a cleanup signal."""
        for sig in (signal.SIGTERM, signal.SIGKILL):
            if self.gone(expected):
                break
            PROCESS_MODULE.signal_checked(expected, sig)
            deadline = time.monotonic() + 2.0
            while time.monotonic() < deadline and not self.gone(expected):
                time.sleep(0.02)
        if child is not None:
            child.wait(timeout=3.0)

    def cleanup_instance(self, workspace, instance):
        # Also recover a forked child if an assertion fails before reading ready.
        # The UUID was generated by this test; never select a process by name alone.
        for actual in PROCESS_MODULE.scan_processes():
            if (actual.workspace_tag == str(workspace) and
                    actual.instance_tag == instance and actual.uid == os.getuid()):
                self.cleanup_owned_process(actual)

    def prepare(self, directory):
        workspace = Path(directory).resolve()
        script = workspace / 'install' / 'machining_demo' / 'lib' / 'machining_demo' / 'task_manager'
        script.parent.mkdir(parents=True)
        script.write_text(NODE_SOURCE, encoding='utf-8')
        environment = os.environ.copy()
        environment['A2_DEMO_WORKSPACE'] = str(workspace)
        environment['A2_DEMO_INSTANCE'] = uuid.uuid4().hex
        self.addCleanup(self.cleanup_instance, workspace, environment['A2_DEMO_INSTANCE'])
        return workspace, script, environment

    def start(self, workspace, script, environment, mode, ready):
        child = subprocess.Popen(
            [sys.executable, str(script), mode, str(ready)], cwd=str(workspace),
            env=environment, start_new_session=True,
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        expected = self.identity(child.pid)
        self.assertIsNotNone(expected)
        self.addCleanup(self.cleanup_owned_process, expected, child)
        return child, expected

    def stop(self, workspace):
        with redirect_stdout(io.StringIO()):
            PROCESS_MODULE.stop_workspace(str(workspace))

    def test_tagged_node_really_exits_using_proc_and_pidfd(self):
        with tempfile.TemporaryDirectory(prefix='a2_shutdown_node_') as directory:
            workspace, script, environment = self.prepare(directory)
            ready = workspace / 'node.ready'
            child, expected = self.start(workspace, script, environment, 'node', ready)
            self.wait_for(ready.exists, 'node signal handler')
            actual = self.identity(child.pid)
            self.assertEqual(actual.workspace_tag, str(workspace))
            self.assertEqual(actual.instance_tag, environment['A2_DEMO_INSTANCE'])
            self.assertEqual(actual.sid, child.pid)
            self.assertEqual(actual.pgid, child.pid)
            self.assertTrue(PROCESS_MODULE.same_identity(expected, actual))
            self.stop(workspace)
            self.assertEqual(child.wait(timeout=3.0), 0)
            self.assertTrue(self.gone(expected))

    def test_orphan_node_really_exits_after_session_leader_exits(self):
        with tempfile.TemporaryDirectory(prefix='a2_shutdown_orphan_') as directory:
            workspace, script, environment = self.prepare(directory)
            ready = workspace / 'orphan.ready'
            launcher, _ = self.start(workspace, script, environment, 'orphan', ready)
            self.wait_for(ready.exists, 'orphan signal handler')
            self.assertEqual(launcher.wait(timeout=3.0), 0)
            pid = int(ready.read_text())
            orphan = self.identity(pid)
            self.assertIsNotNone(orphan)
            self.addCleanup(self.cleanup_owned_process, orphan)
            self.assertNotEqual(orphan.pid, launcher.pid)
            self.assertEqual(orphan.sid, launcher.pid)
            self.assertEqual(orphan.pgid, launcher.pid)
            self.assertEqual(orphan.instance_tag, environment['A2_DEMO_INSTANCE'])
            self.stop(workspace)
            self.wait_for(lambda: self.gone(orphan), 'orphan to exit')


if __name__ == '__main__':
    unittest.main()
